#!/usr/bin/env python3
"""Writes src/ui/TranslationCoverage.h: how much of each language is done,
for Settings' language picker ("Deutsch — 64% translated" until 100%).

Rerun after translating (the Translations test fails until you do):

    python3 scripts/translation-coverage.py
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/ui/TranslationCoverage.h"
LANGUAGES = ["de", "es", "fr", "it", "ja", "nl", "no", "pt", "sv", "zh"]


def finished(message: ET.Element) -> bool:
    t = message.find("translation")
    if t is None or t.get("type") in ("unfinished", "vanished", "obsolete"):
        return False
    forms = t.findall("numerusform")
    if forms:
        return all((f.text or "").strip() for f in forms)
    return bool((t.text or "").strip())


def coverage(code: str) -> int:
    messages = list(ET.parse(ROOT / f"translations/bld_{code}.ts").iter("message"))
    done = sum(1 for m in messages if finished(m))
    # Rounded down: 100 only when every string is done.
    return done * 100 // len(messages) if messages else 0


def main() -> int:
    rows = "\n".join(f'        {{ "{code}", {coverage(code)} }},' for code in LANGUAGES)
    OUT.write_text(
        f"""#pragma once

// Generated by scripts/translation-coverage.py from translations/*.ts.
// Don't edit; rerun the script after translating.

#include <QString>

namespace bld::ui {{

// How much of a language is translated, in percent, rounded down (100:
// every string). English, or a language not listed: 100.
inline int translationPercent(const QString& code) {{
    static const struct {{
        const char* code;
        int percent;
    }} kCoverage[] = {{
{rows}
    }};
    for (const auto& c : kCoverage)
        if (code == QLatin1String(c.code)) return c.percent;
    return 100;
}}

}}  // namespace bld::ui
""",
        encoding="utf-8",
    )
    print(OUT.read_text(encoding="utf-8").split("kCoverage[] = {")[1].split("};")[0])
    return 0


if __name__ == "__main__":
    sys.exit(main())
