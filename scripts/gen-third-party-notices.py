#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.txt: the licenses of what the app links or embeds.

The app is GPL-3.0 (LICENSE). Linked into it on every platform, statically:
yffi/yrs (the live-sync library) with the Rust crates they use, and
QtKeychain. Embedded: the Figtree, Bricolage Grotesque and Liberation Sans
fonts. Qt itself is listed in Help > About Qt.

Run it from the repo root after a build has fetched the dependencies (or
after bumping yffi or QtKeychain in src/sync/CMakeLists.txt):

    scripts/gen-third-party-notices.py <build dir>

With --check it only says whether the committed file is current (CI runs
that on Linux after the build).
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.txt"

# The targets the app ships for; a crate only one of them links still counts.
TARGETS = [
    "x86_64-unknown-linux-gnu",
    "x86_64-pc-windows-msvc",
    "aarch64-apple-darwin",
    "x86_64-apple-darwin",
]

# Crates whose package carries no license file: the project's own.
FALLBACK = {
    "yffi": ROOT / "packaging/licenses/y-crdt-LICENSE.txt",
    "yrs": ROOT / "packaging/licenses/y-crdt-LICENSE.txt",
}

LICENSE_NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")


def linked_crates(yffi_src: Path) -> dict[str, dict]:
    crates: dict[str, dict] = {}
    for target in TARGETS:
        meta = json.loads(subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--offline",
             "--filter-platform", target, "--manifest-path", str(yffi_src / "Cargo.toml")],
            text=True))
        packages = {p["id"]: p for p in meta["packages"]}
        nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        stack, seen = [meta["resolve"]["root"]], set()
        while stack:
            node = stack.pop()
            if node in seen:
                continue
            seen.add(node)
            if is_proc_macro(packages[node]):
                continue
            for dep in nodes[node]["deps"]:
                # Normal dependencies only: build scripts and proc-macros
                # run while building and aren't in the library.
                if any(k["kind"] is None for k in dep["dep_kinds"]):
                    stack.append(dep["pkg"])
        for node in seen:
            p = packages[node]
            if not is_proc_macro(p):
                crates[f'{p["name"]} {p["version"]}'] = p
    return crates


def is_proc_macro(package: dict) -> bool:
    return "proc-macro" in {k for t in package["targets"] for k in t["kind"]}


def license_texts(package: dict) -> list[str]:
    folder = Path(package["manifest_path"]).parent
    files = sorted(f for f in folder.iterdir()
                   if f.is_file() and f.name.upper().startswith(LICENSE_NAMES))
    # "MIT OR Apache-2.0" (and the like): the app takes it under MIT, so its
    # MIT text is the one to include; other licenses AND-ed on stay.
    expr = package.get("license") or ""
    if " OR " in expr and "MIT" in expr.replace("(", " ").replace(")", " ").split():
        mit = [f for f in files if "MIT" in f.name.upper()]
        others = [f for f in files if not any(x in f.name.upper() for x in ("MIT", "APACHE", "COPYING", "UNLICENSE"))
                  and "THIRD-PARTY" not in f.name.upper()]
        if mit:
            files = mit + [f for f in others if expr.count("AND")]
    if not files and package["name"] in FALLBACK:
        files = [FALLBACK[package["name"]]]
    if not files:
        raise SystemExit(f'{package["name"]} {package["version"]}: no license file to include')
    return [f.read_text(encoding="utf-8", errors="replace").strip() for f in files]


def render(build: Path) -> str:
    deps = build / "_deps"
    yffi_src = deps / "yffi-src"
    qtkeychain_src = deps / "qtkeychain-src"
    rule = "=" * 78
    out = [
        "Third-party notices for Collaborative Brick Layout Designer",
        "",
        "The app itself is free software under the GNU General Public License,",
        "version 3 (see LICENSE). It includes the components below, each under its",
        "own license, reproduced here as those licenses ask. Qt is listed in",
        "Help > About Qt.",
        "",
        "Generated by scripts/gen-third-party-notices.py; do not edit by hand.",
        "",
    ]

    def section(title: str, url: str, license_id: str, texts: list[str]) -> None:
        out.extend([rule, title, url, f"License: {license_id}", rule, ""])
        for t in texts:
            out.extend([t, ""])

    section("QtKeychain 0.15.0 (the sign-in token in the system keychain)",
            "https://github.com/frankosterfeld/qtkeychain", "BSD-3-Clause",
            ["Copyright (c) Frank Osterfeldt and the QtKeychain contributors.",
             (qtkeychain_src / "COPYING").read_text(encoding="utf-8").strip()])

    crates = linked_crates(yffi_src)
    for key in sorted(crates, key=lambda k: (crates[k]["name"].lower(), k)):
        p = crates[key]
        url = p.get("repository") or p.get("homepage") or f'https://crates.io/crates/{p["name"]}'
        what = " (the live-sync library)" if p["name"] in ("yffi", "yrs") else ""
        lic = p.get("license") or "see below"
        if " OR " in lic and "MIT" in lic:
            lic += ", used under MIT"
        section(f"{key}{what}", url, lic, license_texts(p))

    fonts = [
        ("Figtree (interface font)", "https://github.com/erikdkennedy/figtree", "OFL-1.1",
         ROOT / "src/ui/theme/fonts/OFL-Figtree.txt"),
        ("Bricolage Grotesque (heading font)", "https://github.com/ateliertriay/bricolage", "OFL-1.1",
         ROOT / "src/ui/theme/fonts/OFL-BricolageGrotesque.txt"),
        ("Liberation Sans (map text)", "https://github.com/liberationfonts/liberation-fonts", "OFL-1.1",
         ROOT / "src/rendering/fonts/LICENSE"),
    ]
    for title, url, lic, path in fonts:
        section(title, url, lic, [path.read_text(encoding="utf-8").strip()])
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    text = render(Path(args[0]).resolve())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("THIRD-PARTY-NOTICES.txt is out of date: run scripts/gen-third-party-notices.py <build dir>",
                  file=sys.stderr)
            return 1
        print("THIRD-PARTY-NOTICES.txt is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
