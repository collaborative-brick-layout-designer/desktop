#!/usr/bin/env python3
"""Writes src/ui/help/HelpTextStrings.cpp from src/ui/help/help-texts.json.

help-texts.json is shared word for word with the web app, so its text can't
carry tr() calls. This lists every title, short and more text in it, marked
with QT_TRANSLATE_NOOP("HelpTexts", ...), so lupdate puts them in the .ts
files; the app translates them when it reads the file (HelpTexts.cpp). Run
it after changing help-texts.json; HelpTextsTest checks the two match.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
HELP = ROOT / "src/ui/help/help-texts.json"
OUT = ROOT / "src/ui/help/HelpTextStrings.cpp"


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    entries = json.loads(HELP.read_text(encoding="utf-8"))["entries"]
    seen = []
    for e in entries.values():
        for field in ("title", "short", "more"):
            if e[field] not in seen:
                seen.append(e[field])
    lines = [
        "// Generated by scripts/gen-help-strings.py from help-texts.json. Don't edit;",
        "// rerun the script after changing help-texts.json.",
        "",
        '#include "HelpTexts.h"',
        "",
        "#include <QtGlobal>",
        "",
        "namespace bld::ui::help {",
        "",
        "namespace {",
        "",
        "const char* const kStrings[] = {",
    ]
    lines += [f'    QT_TRANSLATE_NOOP("HelpTexts", {c_string(s)}),' for s in seen]
    lines += [
        "};",
        "",
        "}  // namespace",
        "",
        "QStringList sharedHelpStrings() {",
        "    QStringList out;",
        "    for (const char* s : kStrings) out << QString::fromUtf8(s);",
        "    return out;",
        "}",
        "",
        "}  // namespace bld::ui::help",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
